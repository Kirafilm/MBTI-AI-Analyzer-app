// 新測驗的結果計算函數
export function calculateNewPsychologyResult(testId: string, answers: number[]) {
  switch (testId) {
    case "color-personality":
      return calculateColorPersonalityResult(answers);
    case "love-style":
      return calculateLoveStyleResult(answers);
    case "work-style":
      return calculateWorkStyleResult(answers);
    case "creativity-index":
      return calculateCreativityIndexResult(answers);
    default:
      return null;
  }
}

function calculateColorPersonalityResult(answers: number[]) {
  // 性格色彩測驗：紅、藍、綠、黃四種類型
  const redScore = [0, 4, 8, 12, 16].reduce((sum, i) => sum + (answers[i] || 0), 0);
  const blueScore = [1, 5, 9, 13, 17].reduce((sum, i) => sum + (answers[i] || 0), 0);
  const greenScore = [2, 6, 10, 14, 18].reduce((sum, i) => sum + (answers[i] || 0), 0);
  const yellowScore = [3, 7, 11, 15, 19].reduce((sum, i) => sum + (answers[i] || 0), 0);

  const scores = { red: redScore, blue: blueScore, green: greenScore, yellow: yellowScore };
  const maxScore = Math.max(...Object.values(scores));
  const primaryType = Object.keys(scores).find(k => scores[k as keyof typeof scores] === maxScore) || "red";

  return {
    type: primaryType,
    scores,
    description: `你的性格色彩是${primaryType === "red" ? "紅色" : primaryType === "blue" ? "藍色" : primaryType === "green" ? "綠色" : "黃色"}`
  };
}

