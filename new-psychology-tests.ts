function calculateCreativityIndexResult(answers: number[]) {
  // 創意指數測驗：5 種創意類型
  const types = ["artistic", "technical", "conceptual", "practical", "experimental"];
  const scores: Record<string, number> = {};
  
  types.forEach((type, idx) => {
    scores[type] = [idx, idx + 5, idx + 10, idx + 15].reduce((sum, i) => sum + (answers[i] || 0), 0);
  });

  const totalScore = Object.values(scores).reduce((a, b) => a + b, 0);
  const creativityIndex = Math.round((totalScore / 80) * 100);
  const maxScore = Math.max(...Object.values(scores));
  const primaryType = Object.keys(scores).find(k => scores[k] === maxScore) || "artistic";

  return {
    type: primaryType,
    index: creativityIndex,
    scores,
    description: `你的創意指數是 ${creativityIndex}%`
  };
}
