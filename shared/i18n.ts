export type Language = "zh-TW" | "zh-CN" | "en";

/** Locale passed to AI analysis APIs (backend MBTI prompts). */
export type AnalysisLocale = "zh-HK" | "zh-CN" | "en";

export function toAnalysisLocale(language: Language): AnalysisLocale {
  if (language === "zh-TW") return "zh-HK";
  if (language === "zh-CN") return "zh-CN";
  return "en";
}

/** `toLocaleDateString` / `toLocaleString` locale tag for UI dates. */
export function localeForDates(language: Language): string {
  if (language === "zh-TW") return "zh-HK";
  if (language === "zh-CN") return "zh-CN";
  return "en-US";
}

